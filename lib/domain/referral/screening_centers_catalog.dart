  /// Generates a standardized clinical referral letter for outpatient presentation
  static String generateReferralLetter({
    required String patientName,
    required String patientId,
    required int? age,
    required String? gender,
    required RiskResult? result,
    required String? lesionSite,
    required int? lesionDurationDays,
    required List<String> reportedSymptoms,
  }) {
    final buffer = StringBuffer();
    final now = DateTime.now();

    buffer.writeln('====================================================');
    buffer.writeln('    ORAL CANCER CARECONNECT — CLINICAL REFERRAL SLIP');
    buffer.writeln('====================================================');
    buffer.writeln('Date of Referral: ${now.day}/${now.month}/${now.year}');
    buffer.writeln('Generated by: OralCare Pilot Assessment System');
    buffer.writeln('Status: CONFIDENTIAL MEDICAL REFERRAL');
    buffer.writeln('----------------------------------------------------');
    buffer.writeln(
      'TO: The Attending Clinician / Head & Neck OPD / Oral Medicine',
    );
    buffer.writeln('RE: Clinical Examination & Specialist Assessment');
    buffer.writeln('----------------------------------------------------');
    buffer.writeln('PATIENT DEMOGRAPHICS:');
    buffer.writeln(
      '  Patient ID: ${patientId.isNotEmpty ? patientId : "Not registered"}',
    );
    buffer.writeln(
      '  Name: ${patientName.isNotEmpty ? patientName : "Anonymous Patient"}',
    );
    buffer.writeln(
      '  Age: ${age ?? "Unknown"} years  |  Gender: ${gender ?? "Unspecified"}',
    );
    buffer.writeln('----------------------------------------------------');
    buffer.writeln('ASSESSMENT SUMMARY:');
    if (result != null) {
      buffer.writeln(
        '  Provisional Risk Band: ${result.category.label.toUpperCase()} (Score: ${result.totalScore})',
      );
      buffer.writeln(
        '  Urgency Status: ${result.outputState.headline.toUpperCase()}',
      );
      if (result.redFlagPresent) {
        buffer.writeln(
          '  RED FLAG TRIGGER: Persistent lesion or alarming clinical signs detected.',
        );
      }
    } else {
      buffer.writeln(
        '  Assessment: Patient reported active oral lesion requiring direct evaluation.',
      );
    }
    buffer.writeln('----------------------------------------------------');
    buffer.writeln('LESION & SYMPTOMS REPORTED:');
    buffer.writeln('  Site: ${lesionSite ?? "Oral cavity site of concern"}');
    buffer.writeln(
      '  Reported Duration: ${lesionDurationDays != null ? "$lesionDurationDays days" : "Unknown"}',
    );
    if (reportedSymptoms.isNotEmpty) {
      buffer.writeln('  Symptoms: ${reportedSymptoms.join(", ")}');
    }
    buffer.writeln('----------------------------------------------------');
    buffer.writeln('RECOMMENDED CLINICAL ACTION:');
    buffer.writeln(
      '  1. Comprehensive intraoral visual and palpation examination.',
    );
    buffer.writeln('  2. Assessment of regional cervical lymphadenopathy.');
    buffer.writeln(
      '  3. Incisional biopsy / Toluidine blue / Diagnostic imaging if indicated.',
    );
    buffer.writeln(
      '  4. Structured tobacco and areca nut cessation counseling.',
    );
    buffer.writeln('----------------------------------------------------');
    buffer.writeln('CLINICAL SAFETY DISCLAIMER:');
    buffer.writeln(
      'This referral slip is generated from patient-reported symptoms',
    );
    buffer.writeln(
      'and provisional screening algorithms. It does NOT constitute a',
    );
    buffer.writeln(
      'confirmed diagnosis or staging of Oral Squamous Cell Carcinoma.',
    );
    buffer.writeln('====================================================');

    return buffer.toString();
  }
}
