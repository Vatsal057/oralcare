enum CenterType {
  dentalInstitute,
  oncologyCentre,
  oralMedicineOmfs,
  communityScreening,
}

extension CenterTypeX on CenterType {
  String get label => switch (this) {
    CenterType.dentalInstitute => 'Dental Institute / College',
    CenterType.oncologyCentre => 'Comprehensive Cancer Centre',
    CenterType.oralMedicineOmfs => 'Oral Medicine & OMFS Dept',
    CenterType.communityScreening => 'Community Health Centre',
  };
}

